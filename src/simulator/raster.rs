//! Deliberately simple, platform-independent debug lettering, not xochitl layout.
use image::{Rgba, RgbaImage};

pub fn text(image: &mut RgbaImage, text: &str) {
    let (mut x, mut y) = (130, 132);
    for ch in text.chars() {
        if ch == '\n' || x > 706 {
            x = 130;
            y += 28;
            if ch == '\n' {
                continue;
            }
        }
        if ch != ' ' {
            let rows = glyph(ch.to_ascii_uppercase());
            for (row, bits) in rows.iter().enumerate() {
                for col in 0..5 {
                    if bits & (1 << (4 - col)) != 0 {
                        for dy in 0..2 {
                            for dx in 0..2 {
                                let (px, py) = (x + col * 2 + dx, y + row as u32 * 2 + dy);
                                if px < image.width() && py < image.height() {
                                    image.put_pixel(px, py, Rgba([0, 0, 0, 255]));
                                }
                            }
                        }
                    }
                }
            }
        }
        x += 12;
    }
}

